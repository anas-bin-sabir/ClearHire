from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected

from app.db.migrate import alembic_config
from app.db.session import engine


def _check(connection) -> None:
    command.check(alembic_config(connection))


async def test_models_match_migrations():
    """Fails when orm.py changes without a matching Alembic revision."""
    async with engine.connect() as conn:
        try:
            await conn.run_sync(_check)
        except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
            raise AssertionError(f"ORM and migrations differ; run alembic revision --autogenerate\n{exc}")
